"""API contract. The frontend mirrors these in frontend/src/types.ts and docs/api.md.
Change all three together."""
from datetime import datetime
from typing import Literal, Optional

from pydantic import BaseModel, Field

FindingStatus = Literal["eol", "nearing_eol", "supported", "unverified"]


class Citation(BaseModel):
    """Where the technology appears in the syllabus."""
    page: int  # 1-based
    snippet: str  # verbatim text from that page
    bbox: Optional[list[float]] = None  # [x0, y0, x1, y1] in PDF points, for highlighting


class Lifecycle(BaseModel):
    """Facts taken from endoflife.date. Never generated by the LLM."""
    product: str  # endoflife.date slug, e.g. "python"
    cycle: Optional[str] = None  # e.g. "2.7"
    eol_date: Optional[str] = None  # ISO date, or None if no EOL announced
    latest_cycle: Optional[str] = None
    source_url: str  # e.g. https://endoflife.date/python


class ScorePart(BaseModel):
    key: str
    label: str
    points: int
    max: int
    reason: str


class Score(BaseModel):
    total: int
    max: int = 100
    breakdown: list[ScorePart]


class Upgrade(BaseModel):
    """Same-product upgrade derived from endoflife.date (sourced)."""
    target_cycle: str
    source_url: str


class Finding(BaseModel):
    id: str
    technology: str  # as written in the syllabus
    version: Optional[str] = None
    status: FindingStatus
    citations: list[Citation]
    lifecycle: Optional[Lifecycle] = None  # None => unverified
    score: Optional[Score] = None  # None => unverified, "needs manual check"
    upgrade: Optional[Upgrade] = None


class SourceInfo(BaseModel):
    kind: Literal["upload", "sample"]
    filename: str
    pages: int


class Summary(BaseModel):
    eol: int = 0
    nearing_eol: int = 0
    supported: int = 0
    unverified: int = 0


class Analysis(BaseModel):
    id: str
    created_at: datetime
    source: SourceInfo
    summary: Summary
    findings: list[Finding]


class Draft(BaseModel):
    finding_id: str
    text: str
    label: Literal["ai_suggestion"] = "ai_suggestion"
    disclaimer: str = "AI suggestion, not sourced. Review and edit before using."
    model: str


class Sample(BaseModel):
    id: str
    title: str
    description: str


class FeedbackIn(BaseModel):
    role: str = Field(..., max_length=100)  # e.g. "Faculty", "Curriculum reviewer", "Student"
    country: str = Field(..., max_length=100)
    institution: Optional[str] = Field(None, max_length=200)
    rating: int = Field(..., ge=1, le=5)
    comments: Optional[str] = Field(None, max_length=2000)
    would_use: Optional[Literal["yes", "maybe", "no"]] = None
    consent_to_quote: bool = False  # may we quote the comment anonymously ("Faculty, Philippines")
    analysis_id: Optional[str] = None


class FeedbackOut(BaseModel):
    ok: bool = True
    id: int
